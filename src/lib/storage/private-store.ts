import "server-only";

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";

/*
 * Private files (candidate CVs). Never public: they are only ever streamed through
 * an authenticated route. Two backends:
 *   - PRIVATE_STORAGE_S3_BUCKET set → that S3-compatible bucket (must NOT allow public reads),
 *     using the OBJECT_STORAGE_ENDPOINT / REGION / ACCESS_KEY_ID / SECRET_ACCESS_KEY credentials;
 *   - otherwise → a folder on the server's disk (PRIVATE_STORAGE_DIR, default ./storage/private),
 *     which is outside /public so the web server never serves it directly.
 */

function s3Target() {
  const bucket = process.env.PRIVATE_STORAGE_S3_BUCKET?.trim();
  if (!bucket) return null;
  const endpoint = process.env.OBJECT_STORAGE_ENDPOINT?.trim();
  const region = process.env.OBJECT_STORAGE_REGION?.trim();
  const accessKeyId = process.env.OBJECT_STORAGE_ACCESS_KEY_ID?.trim();
  const secretAccessKey = process.env.OBJECT_STORAGE_SECRET_ACCESS_KEY?.trim();
  if (!endpoint || !region || !accessKeyId || !secretAccessKey) {
    throw new Error("PRIVATE_STORAGE_S3_BUCKET needs the OBJECT_STORAGE_* endpoint, region and keys.");
  }
  const client = new S3Client({
    endpoint,
    region,
    forcePathStyle: process.env.OBJECT_STORAGE_FORCE_PATH_STYLE === "true",
    credentials: { accessKeyId, secretAccessKey },
  });
  return { client, bucket };
}

export function privateStorageRoot() {
  // The ignore markers stop the bundler tracing (and shipping) the whole project and its CV folder.
  return path.resolve(/*turbopackIgnore: true*/ process.env.PRIVATE_STORAGE_DIR?.trim() || path.join(/*turbopackIgnore: true*/ process.cwd(), "storage", "private"));
}

/** Keys are generated by the app (folder/uuid.ext); reject anything that could escape the root. */
function safeKey(key: string) {
  const normalized = key.replaceAll("\\", "/");
  if (!/^[a-z0-9-]+(\/[a-z0-9-]+)*\/[0-9a-f-]{36}\.(pdf|docx|doc)$/i.test(normalized)) {
    throw new Error("Invalid private storage key.");
  }
  return normalized;
}

function localPath(key: string) {
  const root = privateStorageRoot();
  const target = path.resolve(/*turbopackIgnore: true*/ root, safeKey(key));
  if (!target.startsWith(root + path.sep)) throw new Error("Invalid private storage key.");
  return target;
}

export async function savePrivateFile(key: string, body: Uint8Array, contentType: string) {
  const s3 = s3Target();
  if (s3) {
    await s3.client.send(new PutObjectCommand({ Bucket: s3.bucket, Key: safeKey(key), Body: body, ContentType: contentType }));
    return;
  }
  const target = localPath(key);
  await mkdir(/*turbopackIgnore: true*/ path.dirname(target), { recursive: true });
  await writeFile(/*turbopackIgnore: true*/ target, body, { flag: "wx" });
}

export async function readPrivateFile(key: string): Promise<Uint8Array> {
  const s3 = s3Target();
  if (s3) {
    const result = await s3.client.send(new GetObjectCommand({ Bucket: s3.bucket, Key: safeKey(key) }));
    if (!result.Body) throw new Error("Private file is empty.");
    return result.Body.transformToByteArray();
  }
  return new Uint8Array(await readFile(/*turbopackIgnore: true*/ localPath(key)));
}

export async function deletePrivateFile(key: string) {
  const s3 = s3Target();
  if (s3) {
    await s3.client.send(new DeleteObjectCommand({ Bucket: s3.bucket, Key: safeKey(key) }));
    return;
  }
  await rm(/*turbopackIgnore: true*/ localPath(key), { force: true });
}
